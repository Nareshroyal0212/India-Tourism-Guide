export function toLocalNumber(value, lang) {
  const map = DIGIT_MAPS[lang];
  const str = typeof value === 'number' ? value.toLocaleString('en-IN') : String(value);
  if (!map) return str;
  return str.replace(/[0-9]/g, (d) => map[+d]);
}

